"""Reference data for the backend.

The product catalogue is **not** here. Products, sellers, prices and offers live
in `data/catalog/products.json`, which `app.catalog` reads; this module holds only
the reference data the database still owns: project templates and the requirement
rules that decide what a job needs.

A requirement addresses the catalogue by `category_slug` — one of the
subcategory slugs the catalogue actually carries. A role the catalogue does not
cover (tiles, lighting, cabinetry, hardware) is seeded with `None` and reported
as uncovered rather than being matched to something that is not the same thing.
"""

from __future__ import annotations

from typing import Any

# --------------------------------------------------------------------------- #
# Project templates + requirement rules
# --------------------------------------------------------------------------- #
def _req(
    role: str,
    category: str,
    mode: str,
    multiplier: str,
    min_qty: str,
    max_qty: str | None,
    quality_min: str,
    required: bool,
    reason: str,
    sort_order: int,
) -> dict[str, Any]:
    return {
        "role": role,
        "category": category,
        "quantity_mode": mode,
        "multiplier": multiplier,
        "min_qty": min_qty,
        "max_qty": max_qty,
        "quality_min": quality_min,
        "required": required,
        "reason_fa": reason,
        "sort_order": sort_order,
    }


